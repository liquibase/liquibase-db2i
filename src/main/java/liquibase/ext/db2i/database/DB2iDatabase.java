package liquibase.ext.db2i.database;

import java.util.Locale;

import liquibase.Scope;
import liquibase.database.DatabaseConnection;
import liquibase.database.core.DB2Database;
import liquibase.exception.DatabaseException;
import liquibase.exception.UnexpectedLiquibaseException;
import liquibase.executor.ExecutorService;
import liquibase.statement.core.RawSqlStatement;
import liquibase.util.StringUtil;

public class DB2iDatabase extends DB2Database {

    @Override
    public int getPriority() {
        return super.getPriority()+5;
    }

    @Override
    public boolean isCorrectDatabaseImplementation(DatabaseConnection conn) throws DatabaseException {
        return conn.getDatabaseProductName().startsWith("DB2 UDB for AS/400");
    }

    @Override
    public String getDefaultDriver(String url) {
        if (url.startsWith("jdbc:as400")) {
            return "com.ibm.as400.access.AS400JDBCDriver";
        }
        return null;
    }

    @Override
    protected String getDefaultDatabaseProductName() {
        return "DB2i";
    }

    @Override
    public String getShortName() {
        return "db2i";
    }

    @Override
    public boolean supportsSchemas() {
        return true;
    }

    @Override
	public boolean supportsBooleanDataType() {
        if (getConnection() == null)
            return false;
        try {
            final Integer countBooleanType = Scope.getCurrentScope().getSingleton(ExecutorService.class).getExecutor("jdbc", this).queryForObject(
                    new RawSqlStatement("select count(*) from sysibm.sqltypeinfo where type_name = 'BOOLEAN'"),
                    Integer.class);
            return countBooleanType == 1;
        } catch (final Exception e) {
            Scope.getCurrentScope().getLog(getClass()).info("Error checking for BOOLEAN type", e);
        }
        return false;
    }

    /**
     * Respects {@code generationType} (ALWAYS or BY DEFAULT), which liquibase-core ignores for DB2. Without a
     * generationType the clause is {@code GENERATED BY DEFAULT AS IDENTITY}, as before. START WITH and INCREMENT BY
     * are still added by liquibase-core.
     * <p>
     * {@code defaultOnNull} is ignored, as IBM i has no {@code ON NULL} clause.
     *
     * @throws UnexpectedLiquibaseException if generationType is neither ALWAYS nor BY DEFAULT
     */
    @Override
    protected String getAutoIncrementClause(final String generationType, final Boolean defaultOnNull) {
        if (StringUtil.isEmpty(generationType)) {
            return super.getAutoIncrementClause(generationType, defaultOnNull);
        }
        String type = generationType.trim().toUpperCase(Locale.ROOT).replaceAll("\\s+", " ");
        if (!type.equals("ALWAYS") && !type.equals("BY DEFAULT")) {
            throw new UnexpectedLiquibaseException("Unsupported generationType for db2i: '" + generationType
                    + "'. Allowed values are ALWAYS and BY DEFAULT.");
        }
        return "GENERATED " + type + " AS IDENTITY";
    }
}
