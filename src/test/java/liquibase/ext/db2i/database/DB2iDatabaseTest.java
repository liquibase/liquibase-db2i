package liquibase.ext.db2i.database;

import liquibase.exception.UnexpectedLiquibaseException;
import org.junit.Test;

import java.math.BigInteger;

import static junit.framework.TestCase.assertEquals;
import static junit.framework.TestCase.assertFalse;
import static junit.framework.TestCase.assertTrue;

public class DB2iDatabaseTest {

    private static String clause(Integer startWith, Integer incrementBy, String generationType) {
        return new DB2iDatabase().getAutoIncrementClause(
                startWith == null ? null : BigInteger.valueOf(startWith),
                incrementBy == null ? null : BigInteger.valueOf(incrementBy),
                generationType, null);
    }

    @Test
    public void getShortName() {
        assertEquals("db2i", new DB2iDatabase().getShortName());
    }

    @Test
    public void autoIncrementWithoutAttributes() {
        assertEquals("GENERATED BY DEFAULT AS IDENTITY", clause(null, null, null));
    }

    @Test
    public void autoIncrementWithStartAndIncrementWithoutGenerationType() {
        assertEquals("GENERATED BY DEFAULT AS IDENTITY (START WITH 100, INCREMENT BY 5)", clause(100, 5, null));
    }

    @Test
    public void autoIncrementWithGenerationTypeOnly() {
        assertEquals("GENERATED ALWAYS AS IDENTITY", clause(null, null, "ALWAYS"));
        assertEquals("GENERATED BY DEFAULT AS IDENTITY", clause(null, null, "BY DEFAULT"));
    }

    @Test
    public void autoIncrementWithAllAttributes() {
        assertEquals("GENERATED ALWAYS AS IDENTITY (START WITH 100, INCREMENT BY 5)", clause(100, 5, "ALWAYS"));
    }

    @Test
    public void generationTypeIsNormalized() {
        assertEquals("GENERATED BY DEFAULT AS IDENTITY", clause(null, null, " by  default "));
        assertEquals("GENERATED ALWAYS AS IDENTITY", clause(null, null, "always"));
    }

    @Test
    public void emptyGenerationTypeMeansByDefault() {
        assertEquals("GENERATED BY DEFAULT AS IDENTITY", clause(null, null, ""));
    }

    @Test
    public void autoIncrementClauseNeverContainsNull() {
        BigInteger[] numbers = {null, BigInteger.ONE, BigInteger.valueOf(100)};
        String[] generationTypes = {null, "", "ALWAYS", "BY DEFAULT"};
        Boolean[] defaultOnNulls = {null, true, false};
        for (BigInteger startWith : numbers) {
            for (BigInteger incrementBy : numbers) {
                for (String generationType : generationTypes) {
                    for (Boolean defaultOnNull : defaultOnNulls) {
                        String clause = new DB2iDatabase().getAutoIncrementClause(startWith, incrementBy,
                                generationType, defaultOnNull);
                        String context = clause + " <- " + startWith + ", " + incrementBy + ", " + generationType
                                + ", " + defaultOnNull;
                        assertTrue(context, clause.startsWith("GENERATED "));
                        assertFalse(context, clause.contains("null"));
                    }
                }
            }
        }
    }

    @Test(expected = UnexpectedLiquibaseException.class)
    public void unsupportedGenerationTypeIsRejected() {
        clause(null, null, "SOMETIMES");
    }
}
