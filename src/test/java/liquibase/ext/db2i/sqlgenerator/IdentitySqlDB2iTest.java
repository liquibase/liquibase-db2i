package liquibase.ext.db2i.sqlgenerator;

import liquibase.datatype.DataTypeFactory;
import liquibase.ext.db2i.database.DB2iDatabase;
import liquibase.sql.Sql;
import liquibase.sqlgenerator.SqlGeneratorFactory;
import liquibase.statement.AutoIncrementConstraint;
import liquibase.statement.core.AddAutoIncrementStatement;
import liquibase.statement.core.CreateTableStatement;
import org.junit.Test;

import java.math.BigInteger;

import static org.junit.Assert.assertTrue;

/**
 * The identity clause of {@link DB2iDatabase} as it ends up in createTable and addAutoIncrement.
 */
public class IdentitySqlDB2iTest {

    private final DB2iDatabase database = new DB2iDatabase();

    private String sql(liquibase.statement.SqlStatement statement) {
        StringBuilder sb = new StringBuilder();
        for (Sql sql : SqlGeneratorFactory.getInstance().generateSql(statement, database)) {
            sb.append(sql.toSql()).append(";\n");
        }
        return sb.toString();
    }

    @Test
    public void createTableWithoutIdentityAttributes() {
        CreateTableStatement statement = new CreateTableStatement(null, null, "T");
        statement.addColumn("ID", DataTypeFactory.getInstance().fromDescription("INT", database),
                new AutoIncrementConstraint("ID"));
        String sql = sql(statement);
        assertTrue(sql, sql.contains("ID INTEGER GENERATED BY DEFAULT AS IDENTITY"));
    }

    @Test
    public void createTableWithAllIdentityAttributes() {
        CreateTableStatement statement = new CreateTableStatement(null, null, "T");
        statement.addColumn("ID", DataTypeFactory.getInstance().fromDescription("INT", database),
                new AutoIncrementConstraint("ID", BigInteger.valueOf(100), BigInteger.valueOf(5), "ALWAYS", null));
        String sql = sql(statement);
        assertTrue(sql, sql.contains(
                "ID INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 100, INCREMENT BY 5)"));
    }

    @Test
    public void addAutoIncrement() {
        String sql = sql(new AddAutoIncrementStatement(null, null, "T", "ID", "INT",
                BigInteger.valueOf(100), null, null, null));
        assertTrue(sql, sql.contains("GENERATED BY DEFAULT AS IDENTITY (START WITH 100)"));
        assertTrue(sql, !sql.contains("null"));
    }

    @Test
    public void addAutoIncrementWithGenerationTypeAlways() {
        String sql = sql(new AddAutoIncrementStatement(null, null, "T", "ID", "INT",
                null, null, null, "ALWAYS"));
        assertTrue(sql, sql.contains("GENERATED ALWAYS AS IDENTITY"));
    }
}
